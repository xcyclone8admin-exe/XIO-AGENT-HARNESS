#!/usr/bin/env node
// Generates git-ignored module registries for the web app and the sidecar (ADR-0006).
// Scans modules/*/package.json; validates ids, dependsOn topology and export layout.
// Adding a module never requires editing a shared file.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const modulesDir = path.join(root, 'modules');

export function discoverModules(dir = modulesDir) {
  if (!fs.existsSync(dir)) return [];
  const found = [];
  for (const name of fs.readdirSync(dir).sort()) {
    const pkgPath = path.join(dir, name, 'package.json');
    if (!fs.existsSync(pkgPath)) continue;
    const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
    const meta = pkg.xyraModule;
    if (!meta) throw new Error(`modules/${name}/package.json lacks "xyraModule"`);
    if (meta.id !== name) throw new Error(`modules/${name}: xyraModule.id "${meta.id}" must equal directory name`);
    if (!/^[a-z][a-z0-9-]*$/.test(meta.id)) throw new Error(`modules/${name}: invalid id`);
    if (pkg.name !== `@xyra/mod-${name}`) throw new Error(`modules/${name}: package name must be @xyra/mod-${name}`);
    const has = (sub) => fs.existsSync(path.join(dir, name, sub));
    found.push({
      id: meta.id,
      pkg: pkg.name,
      dependsOn: meta.dependsOn ?? [],
      hasServer: has('server/index.ts'),
      hasUi: has('ui/index.tsx') || has('ui/index.ts'),
      hasSample: has('sample/index.ts'),
      hasMigrations: has('migrations'),
    });
  }
  return found;
}

export function topoSort(mods) {
  const byId = new Map(mods.map((m) => [m.id, m]));
  const order = [];
  const state = new Map();
  const visit = (id, trail) => {
    const s = state.get(id);
    if (s === 'done') return;
    if (s === 'visiting') throw new Error(`Module dependency cycle: ${[...trail, id].join(' -> ')}`);
    const m = byId.get(id);
    if (!m) throw new Error(`Unknown module dependency "${id}" (from ${trail.at(-1)})`);
    state.set(id, 'visiting');
    for (const d of m.dependsOn) visit(d, [...trail, id]);
    state.set(id, 'done');
    order.push(m);
  };
  for (const m of mods) visit(m.id, []);
  return order;
}

/** Platform migrations first, then each module's in topological order. Files: NNNN_snake_name.sql */
export function collectMigrations(orderedMods) {
  const sources = [{ module: 'platform', dir: path.join(root, 'packages/db/migrations') }];
  for (const m of orderedMods) if (m.hasMigrations) sources.push({ module: m.id, dir: path.join(modulesDir, m.id, 'migrations') });
  const out = [];
  for (const { module, dir } of sources) {
    if (!fs.existsSync(dir)) continue;
    const files = fs.readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
    let prev = 0;
    for (const f of files) {
      const match = /^(\d{4})_[a-z0-9_]+\.sql$/.exec(f);
      if (!match) throw new Error(`${module}: migration "${f}" must be named NNNN_snake_case.sql`);
      const seq = Number(match[1]);
      if (seq !== prev + 1) throw new Error(`${module}: migration sequence gap before "${f}"`);
      prev = seq;
      const sql = fs.readFileSync(path.join(dir, f), 'utf8').replace(/\r\n/g, '\n');
      out.push({ id: `${module}/${f.replace(/\.sql$/, '')}`, module, sql, checksum: createHash('sha256').update(sql).digest('hex') });
    }
  }
  return out;
}

function write(file, text) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const prev = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (prev !== text) fs.writeFileSync(file, text);
}

export function generate() {
  const mods = topoSort(discoverModules());
  const header = '// GENERATED by tools/gen-module-registry.mjs — do not edit.\n';
  const ids = JSON.stringify(mods.map((m) => m.id));

  const web = [
    header,
    "import type { ModuleUi } from '@xyra/sdk/module-ui';",
    "import type { ModuleManifest } from '@xyra/contracts';",
    ...mods.map((m, i) => `import manifest${i} from '${m.pkg}/manifest';`),
    '',
    `export const MODULE_IDS = ${ids} as const;`,
    'export const MANIFESTS: readonly ModuleManifest[] = [' + mods.map((_, i) => `manifest${i}`).join(', ') + '];',
    'export const UI_LOADERS: Readonly<Record<string, () => Promise<{ default: ModuleUi }>>> = {',
    ...mods.filter((m) => m.hasUi).map((m) => `  '${m.id}': () => import('${m.pkg}/ui'),`),
    '};',
    '',
  ].join('\n');

  const sidecar = [
    header,
    "import type { ModuleServer } from '../modules/types';",
    "import type { ModuleManifest } from '@xyra/contracts';",
    ...mods.map((m, i) => `import manifest${i} from '${m.pkg}/manifest';`),
    ...mods.filter((m) => m.hasServer).map((m) => `import server_${m.id.replace(/-/g, '_')} from '${m.pkg}/server';`),
    ...mods.filter((m) => m.hasSample).map((m) => `import sample_${m.id.replace(/-/g, '_')} from '${m.pkg}/sample';`),
    '',
    `export const MODULE_IDS = ${ids} as const;`,
    'export const MANIFESTS: readonly ModuleManifest[] = [' + mods.map((_, i) => `manifest${i}`).join(', ') + '];',
    'export const SERVERS: readonly ModuleServer[] = [' +
      mods.filter((m) => m.hasServer).map((m) => `server_${m.id.replace(/-/g, '_')}`).join(', ') +
      '];',
    'export const SAMPLES = {' +
      mods.filter((m) => m.hasSample).map((m) => ` '${m.id}': sample_${m.id.replace(/-/g, '_')},`).join('') +
      ' } as const;',
    '',
  ].join('\n');

  const migrationList = collectMigrations(mods);
  const migrations = [
    header,
    "import type { Migration } from '@xyra/db';",
    'export const MIGRATIONS: readonly Migration[] = ' + JSON.stringify(migrationList, null, 2) + ';',
    '',
  ].join('\n');

  write(path.join(root, 'apps/web/src/generated/modules.ts'), web);
  write(path.join(root, 'apps/sidecar/src/generated/modules.ts'), sidecar);
  write(path.join(root, 'apps/sidecar/src/generated/migrations.ts'), migrations);
  return mods.map((m) => m.id);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const ids = generate();
  console.log(`module registry: ${ids.length} modules [${ids.join(', ')}]`);
}
