import { writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { z } from 'zod';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = existsSync(join(__dirname, '..', 'package.json'))
  ? join(__dirname, '..')
  : join(__dirname, '..', '..');

const runtimeDir = join(ROOT, 'packages', 'runtime', 'schema');
const brainDir = join(ROOT, 'packages', 'brain', 'schema');
const webDir = join(ROOT, 'apps', 'web', 'src', 'schema');

for (const d of [runtimeDir, brainDir, webDir]) {
  if (!existsSync(d)) mkdirSync(d, { recursive: true });
}

async function main() {
  let exports;
  try {
    const mod = await import('file://' + join(ROOT, 'packages/contracts/src/index.ts'));
    exports = mod;
  } catch (err) {
    console.error('[gen-type-translations] could not import contracts:', err.message);
    process.exitCode = 1;
    return;
  }

  const emitted = [];
  const skipped = [];
  const ZOD = [
    'ZodObject','ZodArray','ZodEnum','ZodLiteral','ZodString','ZodNumber',
    'ZodBoolean','ZodDate','ZodOptional','ZodNullable','ZodDefault',
    'ZodTransform','ZodEffects','ZodRecord','ZodTuple','ZodUnion',
    'ZodIntersection','ZodLazy','ZodReadonly',
  ];

  for (const [name, value] of Object.entries(exports)) {
    if (!value || typeof value !== 'object') continue;
    const cn = value.constructor && value.constructor.name;
    if (ZOD.includes(cn) || value.shape !== undefined) {
      try { emit(name, value); emitted.push(name); }
      catch (e) { skipped.push(name + ': ' + e.message); }
    }
  }
  for (const [name, value] of Object.entries(exports)) {
    if (skipped.some(s => s.startsWith(name + ':')) || emitted.includes(name)) continue;
    if (value && typeof value === 'object' && value.options !== undefined && value.enum !== undefined) {
      try { emit(name, value); emitted.push(name); }
      catch (e) { skipped.push(name + ': ' + e.message); }
    }
  }

  console.log('[gen-type-translations] emitted ' + emitted.length + ' translations');
  if (skipped.length) console.warn('[gen-type-translations] skipped:', skipped.join(', '));
}

function emit(name, schema) {
  const safe = name.replace(/[^a-zA-Z0-9_]/g, '_');
  const T = safe.charAt(0).toUpperCase() + safe.slice(1);
  const dts =
    '// GENERATED by tools/gen-type-translations.mjs - do not edit.\n' +
    '// Source: packages/contracts/src/' + name + '\n' +
    'export type ' + T + ' = z.input<typeof ' + safe + '>;\n' +
    'export type ' + T + 'Output = z.output<typeof ' + safe + '>;\n';
  writeFileSync(join(runtimeDir, safe + '.d.ts'), dts);
  writeFileSync(join(brainDir, safe + '.d.ts'), dts);
  const web =
    '// GENERATED by tools/gen-type-translations.mjs - do not edit.\n' +
    "import { " + safe + " } from '@xyra/contracts';\n" +
    "import type { z } from 'zod';\n" +
    'export type ' + T + ' = z.input<typeof ' + safe + '>;\n' +
    'export type ' + T + 'Output = z.output<typeof ' + safe + '>;\n' +
    'export { ' + safe + ' };\n' +
    'export function ' + T + 'JsonSchema(): unknown {\n' +
    '  return JSON.parse(JSON.stringify(' + safe + '.jsonSchema()));\n' +
    '}\n';
  writeFileSync(join(webDir, safe + '.ts'), web);
}

main();
